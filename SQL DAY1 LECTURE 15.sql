-- CREATE A EXCEL DATA SHEET CONTAINING THE COLUMN NAME DISTRIBUTOR ID , NAME ,CITY,REGION, PHONE
-- TABLE OF DISTRIBUTOR
CREATE TABLE DISTRIBUTORS (
  distributor_id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  city TEXT,
  region TEXT,
  phone TEXT
  );
  --DROPING THE TABLE----
  DROP TABLE DISTRIBUTOR
  
  --CREATE A TABLE WITH A NAME PRODUCT CONTAINING PRODUCT-ID,PRODUCT NAME,BRAND , PRODUCT CATEGORY,PRICE,STOCK--
  CREATE TABLE PRODUCTs(
  product_id INTEGER PRIMARY KEY,
  product_name TEXT NOT NULL UNIQUE,
  brand TEXT,
  category TEXT NOT NULL,
  price REAL CHECK (PRICE>0),
  stock INTEGER DEFAULT 0
  );
  -- CREATE A TABLE CONTAINING SALES AND SHOULD HAVE NAME,SALES_ID,COLUMNS,PRODUCT_ID,DISTRIBUTOR_ID,SALES DATE,QUANTITY,AMOUNT--
  CREATE TABLE SALES(
  sales_id INTEGER PRIMARY KEY,
  product_id INTEGER,
  distributor_id INTEGER,
  sales_date TEXT,
  quantity INTEGER CHECK (QUANTITY>0),
  amount REAL,
  FOREIGN KEY (product_id) REFERENCES product(product_id),
  FOREIGN KEY (distributor_id) REFERENCES distributors(distributor_id)
  ); 
